// Copies web/src/components/templates/templateBuilderConfig.tsx into
// this project's own src/generated/ directory, run automatically before
// this service starts (see package.json's "prestart"/"pretest").
//
// Why a copy, not a live cross-project import: templateBuilderConfig.tsx
// imports "react", and Node resolves that import starting from the
// file's own physical directory upward — for the original file (living
// under web/src/), that always finds web/node_modules/react, while
// react-dom/server (imported by this service) resolves ITS OWN "react"
// dependency from renderer/node_modules/react. Those are two separate
// React installs, and React's hook dispatcher is a module-level
// singleton — two copies in one process breaks every hook call
// ("Invalid hook call... you might have more than one copy of React in
// the same app"), confirmed empirically while wiring this up. Copying
// the file into this project's own src/ tree makes its "react" import
// resolve within this same node_modules, the same single copy
// react-dom/server itself uses — no singleton conflict.
//
// This is a build-time copy of the CURRENT file content, not a
// hand-maintained duplicate: the source of truth stays
// web/src/components/templates/templateBuilderConfig.tsx, and running
// this script (which prestart/pretest already do automatically) is what
// keeps the copy honest — never edit src/generated/ directly.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const sourcePath = path.join(
  __dirname,
  "..",
  "..",
  "web",
  "src",
  "components",
  "templates",
  "templateBuilderConfig.tsx",
);
const outDir = path.join(__dirname, "..", "src", "generated");
const outPath = path.join(outDir, "templateBuilderConfig.tsx");

const source = readFileSync(sourcePath, "utf8");
const banner = `// AUTO-GENERATED by scripts/sync-template-config.mjs — do not edit.\n// Source of truth: web/src/components/templates/templateBuilderConfig.tsx\n// Regenerate with: npm run sync\n\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outPath, banner + source);

console.log(`synced ${sourcePath} -> ${outPath}`);
